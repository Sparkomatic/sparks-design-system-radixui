/**
 * Scans src/tokens/** and writes src/tokens/index.css with @import lines
 * plus a font-name correction block.
 * Runs automatically via predev / prebuild hooks — no manual imports needed.
 */
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join, relative } from "path";

const TOKENS_DIR = "src/tokens";
const OUT_FILE = join(TOKENS_DIR, "index.css");

/**
 * Maps Figma font family names → correct CSS font-family values.
 *
 * Figma uses short display names ("Inter", "Playfair Display") that designers
 * recognise. The @fontsource-variable npm packages register font faces with a
 * "Variable" suffix. This map is the translator between the two — Figma stays
 * readable, the generated CSS uses the correct registered name.
 *
 * Add an entry here whenever you add a new variable font to the project.
 */
const FONT_FAMILY_MAP = {
  "Inter":            "'Inter Variable', sans-serif",
  "Playfair Display": "'Playfair Display Variable', serif",
  "Roboto Mono":      "'Roboto Mono Variable', monospace",
};

function collectCssFiles(dir, base = dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectCssFiles(full, base));
    } else if (entry.name.endsWith(".css") && entry.name !== "index.css") {
      files.push("./" + relative(base, full));
    }
  }
  // Root-level files before subdirectory files, then alphabetical within each group
  return files.sort((a, b) => {
    const aDepth = a.split("/").length;
    const bDepth = b.split("/").length;
    if (aDepth !== bDepth) return aDepth - bDepth;
    return a.localeCompare(b);
  });
}

/**
 * Scans all token CSS files and finds custom properties whose values match
 * a Figma font family name that needs remapping. Returns a Map of
 * CSS property name → corrected font-family value.
 */
function buildFontCorrections(files) {
  const corrections = new Map();
  for (const relPath of files) {
    const absPath = join(TOKENS_DIR, relPath.replace("./", ""));
    const css = readFileSync(absPath, "utf8");
    for (const [figmaName, cssValue] of Object.entries(FONT_FAMILY_MAP)) {
      // Match exactly: --some-var: Inter; (not "Inter Variable" or "Inter, sans-serif")
      const regex = new RegExp(`(--[\\w-]+):\\s*${figmaName}\\s*;`, "g");
      let match;
      while ((match = regex.exec(css)) !== null) {
        corrections.set(match[1], cssValue);
      }
    }
  }
  return corrections;
}

const files = collectCssFiles(TOKENS_DIR);
const imports = files.map((f) => `@import "${f}";`).join("\n");

const fontCorrections = buildFontCorrections(files);
let correctionBlock = "";
if (fontCorrections.size > 0) {
  const props = Array.from(fontCorrections.entries())
    .map(([prop, value]) => `  ${prop}: ${value};`)
    .join("\n");
  correctionBlock = [
    "",
    "/* Font name corrections — Figma names → CSS/npm @fontsource-variable names */",
    "/* Auto-generated from FONT_FAMILY_MAP in scripts/sync-token-imports.mjs   */",
    ":root {",
    props,
    "}",
    "",
  ].join("\n");
}

const content = `/* Auto-generated by scripts/sync-token-imports.mjs — do not edit */\n${imports}\n${correctionBlock}`;
writeFileSync(OUT_FILE, content);
console.log(
  `[sync-tokens] ${files.length} files → src/tokens/index.css` +
  (fontCorrections.size > 0 ? ` (${fontCorrections.size} font correction${fontCorrections.size > 1 ? "s" : ""})` : "")
);
